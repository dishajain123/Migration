import { AlertTriangle, Loader2, Sparkles } from 'lucide-react';
import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Badge, Button, Card, CardHeader } from '@/components/ui';
import { withRateLimitRecovery } from '@/stores/rateLimitStore';
import type { ApiResult, ApiMeta } from '@/types';
import type { AiInsight, ModelChoice } from '@/types/ai';

type State =
  | { status: 'idle' }
  | { status: 'loading' }
  | { status: 'error'; code: string; message: string }
  | { status: 'success'; insight: AiInsight; meta: ApiMeta };

/**
 * Reusable AI result card for any agent. Runs only when the user clicks (each run uses their API quota), resets when
 * `resetKey` changes, and handles idle / loading / error / empty / success. No business logic: `run` comes from a service.
 */
export function AiInsightPanel({ title, run, resetKey, actionLabel = 'Generate with AI' }: {
  title: string; run: (override?: ModelChoice) => Promise<ApiResult<AiInsight>>; resetKey: string; actionLabel?: string;
}) {
  const [state, setState] = useState<State>({ status: 'idle' });
  useEffect(() => { setState({ status: 'idle' }); }, [resetKey]);

  const go = async () => {
    setState({ status: 'loading' });
    const r = await withRateLimitRecovery(run); // opens the provider/model dialog only for HTTP 429
    setState(r.data ? { status: 'success', insight: r.data, meta: r.meta } : { status: 'error', code: r.error?.code ?? 'ERROR', message: r.error?.message ?? 'The AI request failed.' });
  };

  return (
    <Card>
      <CardHeader
        title={<span className="inline-flex items-center gap-1.5"><Sparkles size={14} className="text-primary" /> {title}</span>}
        subtitle="Generated by your selected AI model from workbook data only."
        right={
          <div className="flex items-center gap-2">
            {state.status === 'success' && state.meta.provider && <Badge tone="primary">AI · {state.meta.provider} · {state.meta.model}</Badge>}
            <Button size="sm" variant={state.status === 'success' ? 'outline' : 'default'} onClick={() => void go()} disabled={state.status === 'loading'}>
              {state.status === 'loading' ? <Loader2 size={13} className="animate-spin" /> : <Sparkles size={13} />}
              {state.status === 'loading' ? 'Working...' : state.status === 'success' ? 'Regenerate' : actionLabel}
            </Button>
          </div>
        }
      />
      <div aria-live="polite" className="p-3 text-sm">
        {state.status === 'idle' && <p className="text-muted">Click the button to run the AI on the current selection. Nothing is sent until you do.</p>}
        {state.status === 'loading' && <p className="flex items-center gap-2 text-muted"><Loader2 size={14} className="animate-spin" /> Waiting for the model...</p>}
        {state.status === 'error' && (
          <div role="alert" className="flex items-start gap-2 rounded-md border border-bad bg-badbg p-2 text-bad">
            <AlertTriangle size={15} className="mt-0.5 shrink-0" />
            <div>
              {state.message}
              {(state.code === 'NOT_CONFIGURED' || state.code === 'MISSING_KEY' || state.code === 'INVALID_KEY' || state.code === 'PERMISSION_DENIED' || state.code === 'QUOTA_EXHAUSTED' || state.code === 'INCOMPATIBLE') && (
                <> <Link to="/ai-settings" className="font-medium underline">Open AI Settings</Link></>
              )}
            </div>
          </div>
        )}
        {state.status === 'success' && (
          <div className="space-y-3">
            <p>{state.insight.summary}</p>
            {state.insight.sections.length === 0 && <p className="text-muted">The model returned no detail sections.</p>}
            {state.insight.sections.map((s) => (
              <div key={s.title}>
                <div className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted">{s.title}</div>
                <ul className="list-disc space-y-1 pl-5">{s.points.map((p, i) => <li key={i}>{p}</li>)}</ul>
              </div>
            ))}
            <p className="text-[11px] text-muted">{state.meta.note} Latency {state.meta.latencyMs} ms.</p>
          </div>
        )}
      </div>
    </Card>
  );
}
