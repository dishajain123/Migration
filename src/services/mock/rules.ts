import { procedureRules, traceAll, traceValidation } from '@/domain/procTrace';
import { extractRules } from '@/domain/rules';
import { runValidation } from '@/domain/validate';
import type { ProcSource } from '@/types';
import { getProcSources } from '../procSource';
import { getWorkbook } from '../workbookSource';
import type { RuleService } from '../types';
import { respond } from './respond';

/** Procedure SQL is optional: if the files are absent the workbook-only behaviour is unchanged. */
const optionalProcs = (): Promise<ProcSource[]> => getProcSources().catch(() => []);

export const mockRules: RuleService = {
  listRules: () => respond(async () => {
    const model = await getWorkbook();
    const procs = await optionalProcs();
    return [...extractRules(model), ...procedureRules(procs, traceAll(model, procs))];
  }, { simulated: false, note: 'Rules extracted deterministically from workbook cells and from the sample procedure SQL (not generated by an LLM).' }),
  validate: (req) => respond(async () => {
    const model = await getWorkbook();
    const procs = await optionalProcs();
    const rep = runValidation(model, req);
    const extra = traceValidation(procs, traceAll(model, procs));
    const results = [...rep.results, ...extra];
    const totals = { pass: 0, warn: 0, fail: 0 };
    for (const r of results) totals[r.severity] += 1;
    return { ...rep, results, totals, basis: `${rep.basis}${extra.length ? ' Check C8 traces the sample procedures to TRAQ columns by name.' : ''}` };
  }, { simulated: false, note: 'Deterministic metadata checks, no data profiling.' }),
  submitReview: (id, decision) => respond(() => ({ id, decision }), { simulated: true, note: 'Mock persistence: the decision is stored client-side only.' }),
};
